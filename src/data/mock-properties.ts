export function getPropertyById(id: string): Property | undefined {
  return MOCK_PROPERTIES.find((p) => p.id === id);
}

export function filterProperties(properties: Property[], filters: Record<string, unknown>): Property[] {
  return properties.filter((p) => {
    if (filters.neighborhood && p.neighborhood !== filters.neighborhood) return false;
    if (filters.type && p.type !== filters.type) return false;
    if (filters.transactionType && p.transactionType !== filters.transactionType) return false;
    if (filters.furnished !== undefined && p.furnished !== filters.furnished) return false;
    if (filters.availableNow && !p.availableNow) return false;
    if (filters.minPrice && p.price < (filters.minPrice as number)) return false;
    if (filters.maxPrice && p.price > (filters.maxPrice as number)) return false;
    if (filters.rooms && p.rooms !== (filters.rooms as number)) return false;
    return true;
  });
}
